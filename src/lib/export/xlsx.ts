// CSV (separator „;” – polski Excel, UTF-8 z BOM, CRLF)
// ---------------------------------------------------------------------------

/** Ochrona przed formułami przy otwieraniu CSV w arkuszu (=, +, -, @ na początku). */
function csvCell(value: Cell): string {
  if (value === null || value === undefined) return "";
  let text = typeof value === "number" ? String(value).replace(".", ",") : String(value);
  if (typeof value === "string" && /^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return /[";\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function toCsv(rows: readonly Cell[][]): string {
  return "﻿" + rows.map((r) => r.map(csvCell).join(";")).join("\r\n") + "\r\n";
}

/** ZIP z plikiem CSV na arkusz (nazwa pliku = nazwa arkusza). */
export function buildCsvZip(sheets: readonly Sheet[]): Uint8Array {
  const names = sheetNames(sheets.map((s) => s.name));
  const files: Record<string, Uint8Array> = {};
  sheets.forEach((s, i) => {
    files[`${names[i]}.csv`] = strToU8(toCsv(s.rows));
  });
  return zipSync(files, { level: 6 });
}
